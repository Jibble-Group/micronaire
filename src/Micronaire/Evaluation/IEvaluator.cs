using Micronaire.Evaluation.Interfaces;
using Micronaire.Evaluation.Models;
using Microsoft.SemanticKernel;

namespace Micronaire.Evaluation;

/// <summary>
/// An evaluator for RAG pipelines.
/// </summary>
public interface IEvaluator
{
    /// <summary>
    /// Evaluates the given pipeline using the ground truth data at the given path.
    /// </summary>
    /// <param name="evaluator">The semantic kernel to use for evaluation.</param>
    /// <param name="pipeline">The pipeline to use for evaluation.</param>
    /// <param name="groundTruthPath">The path to json file with ground truth answers and questions.</param>
    /// <returns>An <see cref="EvaluationReport"/> that has all the gathered evaluation data.</returns>
    public Task<EvaluationReport> EvaluateAsync(
        Kernel evaluator,
        IRagPipeline pipeline,
        string groundTruthPath,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Evaluates a single question with LLM-as-a-judge.
    /// </summary>
    /// <param name="evaluator">The semantic kernel to use for evaluation.</param>
    /// <param name="question">The question to evaluate.</param>
    /// <param name="generatedAnswer">The answer generated by the model.</param>
    /// <param name="contexts">The context retrieved by the model.</param>
    /// <returns>A <see cref="QuestionEvaluationReport"/> that has the evaluation data.</returns>
    public Task<QuestionEvaluationReport> EvaluateQuestionAsync(
        Kernel evaluator,
        string question,
        string generatedAnswer,
        List<string> contexts,
        CancellationToken cancellationToken = default);
}